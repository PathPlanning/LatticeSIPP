"""
Data Processing and Visualization Tools for Pathfinding Benchmarks
==================================================================

This module provides a comprehensive suite of tools to process, analyze, and visualize 
the results of dynamic obstacle pathfinding benchmarks. It is designed to be imported 
and used interactively within a Jupyter Notebook.

Key Features:
-------------
1. Data Aggregation: Reads output CSV files generated by the benchmarking scripts and 
   computes relative performance metrics compared to a baseline algorithm.
2. Trajectory Analysis: Calculates exact path lengths, normalized curvature, heading 
   changes, and bending energy based on the used motion primitives (Control Sets).
3. Visualizations: Generates runtime plots overlaid with visual thumbnails of the map 
   scenarios at different obstacle densities.
4. Heatmaps & LaTeX Export: Produces color-coded heatmap tables directly in the terminal 
   for quick analysis, and exports pixel-perfect LaTeX code for academic papers.

Main Functions:
---------------
- process_results_csv()         : Aggregates CSV data into a dictionary of median ratios.
- runtime_plot_with_thumbnails(): Plots relative runtime with visual map snapshots.
- print_heatmap_table()         : Prints colored terminal heatmaps of the results.
- generate_latex_heatmap()      : Generates a standard LaTeX table with heatmap cells.
- generate_latex_blocks()       : Generates a modern LaTeX table with blocked heatmap cells.

Usage Example (in Jupyter Notebook):
------------------------------------
    import processing as pr
    
    # 1. Extract data
    data = pr.process_results_csv(MAP_NAME="arena", BATCHES=[0, 5, 10, 20, 35, 50], PREFIX="./arena/")

    # 2. Plot runtime with map thumbnails
    pr.runtime_plot_with_thumbnails(
        data,
        map_name="arena", 
        obs_type="random", 
        prefix="./arena/", 
        obs_batches=[0, 5, 10, 20, 35, 50]
    )
    
    # 3. Print heatmaps
    pr.print_heatmap_table(data['cost'], "Median Cost (Relative to Baseline)")
    
    # 4. Export to LaTeX for the paper
    latex_code = pr.generate_latex_blocks(data['cost'], "Comparison of Path Costs")
    print(latex_code)
"""

