# --- CORE DATA PROCESSING ---

def load_all_control_sets():
    """
    Loads all primitive sets defined in ALGORITHMS_DATA into memory.
    Returns a dictionary mapping the algorithm ID to its corresponding ControlSet object.
    """
    cs_objects = {}
    for alg_id, (name, path) in ALGORITHMS_DATA.items():
        cs = ControlSet().load_primitives(path)
        cs_objects[alg_id] = cs
    return cs_objects

def calculate_path_length(path_str, control_set):
    """
    Parses the space-separated sequence of primitive IDs from the CSV 
    and computes the exact physical path length using the given ControlSet.
    Ignores negative IDs (which typically indicate wait actions).
    """
    if pd.isna(path_str) or not path_str or control_set is None: 
        return np.nan
    prim_ids = [int(p) for p in str(path_str).split() if (float(p) >= 0 and math.copysign(1, float(p)) > 0)]
    return sum(control_set.get_primitive(pid).length for pid in prim_ids)
    
def process_results_csv(MAP_NAME="arena",
                        BATCHES=[0, 5, 10, 20, 35, 50],
                        PREFIX="./arena/"):
    """
    Reads the generated CSV files for a specific map and calculates median relative metrics.
    
    This function parses raw data, filters for successful runs, normalizes geometric metrics
    (curvature, heading, energy) by path length, and computes ratios relative to the BASELINE_ALG.
    
    Returns:
        dict: A nested structure containing processed metrics ready for plotting or tabular output.
              Format: {'cost': [list of dicts per batch], 'time': [...], ...}
    """
    print(f"[Processing] Aggregating CSVs for map '{MAP_NAME}' from {PREFIX}")
    cs_dict = load_all_control_sets()
    
    table_data = {'cost': [], 'curvature': [], 'heading': [], 'energy': [], 'time': []}
    
    for obs in BATCHES:
        file_path = f"{PREFIX}benchmark_{MAP_NAME}_obs_{obs}.csv"
        if not os.path.exists(file_path):
            print(f"[Warning] File not found, skipping: {file_path}")
            continue
        
        # Load data and strip potential whitespace from algorithm identifiers
        df = pd.read_csv(file_path)
        df['alg'] = df['alg'].str.strip()
        
        # Filter only successful pathfinding tasks
        df_ok = df[df['success'] == 1].copy()
        
        # Calculate real path lengths
        df_ok['length'] = df_ok.apply(lambda row: calculate_path_length(row['path'], cs_dict.get(row['alg'])), axis=1)
        
        # Normalize trajectory metrics by the exact path length to make them comparable
        for metric in ['curvature', 'heading_change', 'bending_energy']:
            df_ok[f'{metric}_norm'] = df_ok[metric] / (df_ok['length'] + EPS)
    
        # Create pivot tables aligning identical tasks across different algorithms
        pivots = {
            'cost':      df_ok.pivot(index='task_id', columns='alg', values='cost'),
            'time':      df_ok.pivot(index='task_id', columns='alg', values='time_sec'),
            'curvature': df_ok.pivot(index='task_id', columns='alg', values='curvature_norm'),
            'heading':   df_ok.pivot(index='task_id', columns='alg', values='heading_change_norm'),
            'energy':    df_ok.pivot(index='task_id', columns='alg', values='bending_energy_norm'),
        }
    
        # Skip batch if the baseline algorithm didn't generate any results
        if BASELINE_ALG not in pivots['cost'].columns:
            print(f"[Warning] Baseline algorithm '{BASELINE_ALG}' missing in batch {obs}.")
            continue
    
        # Initialize iteration results container
        iter_results = {k: {'obstacles': obs} for k in table_data.keys()}
        
        for alg in ALGORITHMS_DATA.keys():
            for key, pivot in pivots.items():
                if alg in pivot.columns:
                    # Create a boolean mask to filter out rows where either the target alg or baseline failed
                    mask = pivot[alg].notna() & pivot[BASELINE_ALG].notna()
                    if mask.any():
                        # Calculate the ratio: Algorithm Value / Baseline Value
                        ratios = pivot.loc[mask, alg] / (pivot.loc[mask, BASELINE_ALG] + EPS)
                        iter_results[key][alg] = ratios.median()
                    else:
                        iter_results[key][alg] = np.nan
                else:
                    iter_results[key][alg] = np.nan
    
        # Append iteration results to the final data structure
        for k in table_data.keys():
            table_data[k].append(iter_results[k])
            
    return table_data


# --- VISUALIZATION & PLOTTING ---

def create_thumbnails(map_name="empty_64_64",
                      obs_type="circle",
                      obs_cs="../data/control_set.txt",
                      output_prefix="./empty_64_64/",
                      obs_batches=[0, 10, 20],
                      fast_draw=False):
    """
    Generates visual snapshots (thumbnails) of the map populated with varying 
    numbers of dynamic obstacles. These images are used to decorate the X-axis 
    of the performance plots.
    """
    print(f"[Thumbnails] Generating map snapshots for {map_name}...")
    cs = ControlSet().load_primitives(obs_cs)
    task_map = Map()
    task_map.read_from_movingai_file(f"../maps/{map_name}.map")
    
    for num_obs in obs_batches:
        obs_set = ObstacleSet().load_dynamic_obstacles(f"../dynamic_obstacles/{map_name}_{obs_type}/dynamic_obstacle_*.txt", cs, num_obs)
        
        # Create the underlying visualizer instance
        update_sim = create_dynamic_visualizer(
            task_map=task_map,
            obstacle_set=obs_set,
            show_path=False,
            fast_draw=fast_draw,
            make_gif=False,
            dpi=150,
            scale=1,
            jupyter_display=False  # Crucial: Disable inline output in Jupyter to avoid clutter
        )
    
        # Extract the Figure object from the visualizer's closure scope.
        # This hack is required because the simulation loop doesn't return the Figure natively.
        fig = None
        for cell in update_sim.__closure__:
            if hasattr(cell.cell_contents, 'savefig'): 
                fig = cell.cell_contents
                break
                
        if fig is None:
            print(f"[Error] Could not extract Figure object from the visualizer for batch {num_obs}.")
            return None
            
        # Trigger the visualizer to render the initial state (tick 0)
        update_sim(0)
    
        # Clean up axes (remove ticks, labels, and borders for a clean minimalistic snapshot)
        for ax in fig.get_axes():
            ax.set_title("")            
            ax.set_xlabel("")           
            ax.set_ylabel("")           
            ax.set_xticks([])           
            ax.set_yticks([])           
            ax.axis('off')
        
        # Save thumbnail
        out_path = f"{output_prefix}/{map_name}_{obs_type}_{num_obs}.png"
        fig.savefig(out_path, bbox_inches='tight', transparent=False, facecolor='white')
        plt.close(fig)
        print(f"  -> Saved {out_path}")


def runtime_plot_with_thumbnails(table_data,
                                 map_name="empty_64_64",
                                 obs_type="circle",
                                 obs_cs="../data/control_set.txt",
                                 prefix="./empty_64_64/",
                                 obs_batches=[0, 10, 20],
                                 fast_draw=False,
                                 plot_prefix=None,
                                 image_zoom=0.128,  # Fine-tuning parameters for canvas rendering
                                 ylim_top=45,
                                 xybox=(0, 90),
                                 bbox_to_anchor=(1.122, 0)):
    """
    Creates an advanced log-scaled runtime performance plot where the X-axis 
    is decorated with actual thumbnail images representing the scenario difficulty 
    (number of dynamic obstacles).
    """
    # 1. Ensure thumbnail images exist
    create_thumbnails(map_name, obs_type, obs_cs, prefix, obs_batches, fast_draw)
    IMAGE_PATHS = {n: f"{prefix}/{map_name}_{obs_type}_{n}.png" for n in obs_batches}
    IMAGE_ZOOM = image_zoom  # Adjust this depending on your screenshot resolutions

    # 2. Fetch and prepare the time data
    # table_data = process_results_csv(map_name, obs_batches, prefix)
    df_time = pd.DataFrame(table_data['time'])
    
    if not df_time.empty:
        plt.figure(figsize=(16, 8), dpi=300)
        ax = plt.gca()
        
        # Create an evenly spaced sequence for the X-axis (0, 1, 2, 3...)
        # This prevents clustering if batches are distributed non-linearly (e.g. 0, 5, 50, 320)
        x_indices = np.arange(len(obs_batches))
        
        for alg in ALGORITHMS_DATA.keys():
            if alg in df_time.columns and not df_time[alg].isna().all():
                display_name = ALGORITHMS_DATA[alg][0]
                style = PLOT_STYLES.get(alg, {'color': 'gray', 'marker': '.'})
                
                # Map actual data values to the evenly spaced X-indices
                y_vals = [df_time.loc[df_time['obstacles'] == b, alg].values[0] 
                          if b in df_time['obstacles'].values else np.nan 
                          for b in obs_batches]
                
                plt.plot(x_indices, y_vals, 
                         label=display_name, 
                         color=style['color'], marker=style['marker'], 
                         linewidth=2.5, markersize=9, alpha=0.9)
    
        # 3. Axis Formatting (Log Scale for Time)
        plt.yscale('log')
        ax.yaxis.set_major_formatter(ticker.ScalarFormatter())
        ax.set_yticks([1.0, 2.0, 5.0, 10.0, 20.0, 40.0])
        ax.set_ylim(0.5, ylim_top)
    
        # X-Axis Layout Adjustments
        x_margin = 0.45  # Margin ratio (0.5 = half the distance between ticks). 
        
        # Establish boundaries so images don't clip at the edges
        ax.set_xlim(x_indices[0] - x_margin, x_indices[-1] + x_margin)
        ax.set_xticks(x_indices) 
        ax.set_xticklabels(obs_batches)
    
        plt.xlabel("Number of dynamic obstacles", fontsize=19, labelpad=12) 
        plt.ylabel(f"Relative Time (x)", fontsize=19, labelpad=10)
        ax.tick_params(axis='both', which='major', labelsize=19)
        
        # 4. Attach Thumbnail Images ABOVE the plot
        for i, obs in enumerate(obs_batches):
            path = IMAGE_PATHS.get(obs)
            if path and os.path.exists(path):
                img = mpimg.imread(path)
                imagebox = OffsetImage(img, zoom=IMAGE_ZOOM)
                
                # Coordinates: x matches the index, y relies on 'axes fraction' mapping it to the top
                ab = AnnotationBbox(imagebox, (i, 1.0),
                                    xybox=xybox, # Vertical offset in points (above the top axis)
                                    xycoords=('data', 'axes fraction'),
                                    boxcoords="offset points",
                                    frameon=True, pad=0.2) 
                ax.add_artist(ab)
    
        # 5. Final Aesthetic Touches
        plt.axhline(1.0, color='red', linestyle='--', alpha=0.5, label='Baseline')
        plt.grid(True, which="both", ls="-", alpha=0.35)
        
        # Legend styling
        plt.legend(loc='lower right', frameon=True, shadow=True, fontsize=16, bbox_to_anchor=bbox_to_anchor)
        plt.tight_layout()
        
        if plot_prefix:
            output_png = f"{plot_prefix}{map_name}_{obs_type}_runtime.png"
            plt.savefig(output_png, bbox_inches='tight', transparent=False, facecolor='white')
            print(f"[Plotting] Saved {output_png}")
        plt.show()


# --- TERMINAL & LATEX HEATMAP GENERATORS ---

def get_flexible_gradient_bg(val, min_val, max_val, log_iters=0, exp_iters=0, gamma=1.0):
    """
    Computes an RGB color tuple for a heatmap cell based on a normalized value.
    The gradient traverses from Green (low values/best) to Yellow to Red (high values/worst).
    
    Parameters:
        val: The metric value of the current cell.
        min_val, max_val: Row minimum and maximum values for local normalization.
        log_iters, exp_iters, gamma: Mathematical transformations applied to adjust 
                                     the color distribution (stretching/compressing).
                                     
    Returns:
        tuple: (R, G, B) integer values between 0 and 255.
    """
    if pd.isna(val) or max_val <= min_val or val <= 0:
        return 245, 245, 245 # Return light gray for null/invalid values
        
    # 1. Base linear normalization into the [0.0, 1.0] domain
    t = (val - min_val) / (max_val - min_val)
    t = max(0.0, min(1.0, t))
    
    # 2. Logarithmic stretch (pushes colors towards lower end)
    for _ in range(log_iters):
        t = math.log1p(t) / math.log1p(1.0)
        
    # 3. Exponential stretch (pushes colors towards higher end)
    for _ in range(exp_iters):
        t = (math.exp(t) - 1.0) / (math.exp(1.0) - 1.0)
        
    # 4. Gamma correction
    if gamma != 1.0:
        t = math.pow(t, gamma)
        
    # 5. Classic Gradient Mapping: Green (0.0) -> Yellow (0.5) -> Red (1.0)
    # Brightness is slightly dampened (max 220) on the green channel to ensure 
    # white/light text remains highly readable.
    if t <= 0.5:
        r = int(255 * (t * 2))
        g = 220  # Slightly darkened green for contrast
    else:
        r = 255
        g = int(220 * (1 - (t - 0.5) * 2))
    b = 50  # Introduce a hint of blue to prevent overly "acidic" neon tones

    return r, g, b

def print_heatmap_table(data, title):
    """
    Renders a colored heatmap table directly in the terminal using ANSI escape codes.
    Color normalization is applied independently per row.
    """
    print(f"\n>>> {title}")
    print("=" * 90)
    
    alg_keys = list(ALGORITHMS_DATA.keys())
    headers = ["obstacles"] + [ALGORITHMS_DATA[k][0] for k in alg_keys]
    header_fmt = "{:>10} " + " ".join(["{:>12}"] * len(alg_keys))
    print(header_fmt.format(*headers))
    
    for row in data:
        vals = [row.get(alg, np.nan) for alg in alg_keys]
        valid_vals = [v for v in vals if pd.notnull(v) and v > 0]
        
        if not valid_vals:
            continue
            
        row_min, row_max = min(valid_vals), max(valid_vals)
        
        str_row = []
        for v in vals:
            if pd.isna(v) or v <= 0:
                str_row.append(f"{'—':>12}")
            else:
                # Apply gradient stretches for better visual contrast distribution
                r, g, b = get_flexible_gradient_bg(
                    v, row_min, row_max, 
                    log_iters=5,    
                    exp_iters=0,    
                    gamma=0.7       
                )
                # ANSI formatting: 48;2;R;G;B is for background, 99 is black text, 1 is bold
                color_code = f"\033[48;2;{r};{g};{b}m\033[99m\033[1m"
                reset_code = "\033[0m" if color_code else ""
                
                # Center the text inside the colored block for a cleaner look
                text = f"{v:.3f}x"
                padded_text = f"{text:^12}" 
                
                # Apply color encompassing padding spaces to create a solid block effect
                str_row.append(f"{color_code}{padded_text}{reset_code}")
                
        print(f"{row.get('obstacles', '-'):>10} " + " ".join(str_row))
    print("=" * 90)

def generate_latex_heatmap(data, title):
    """
    Generates a raw LaTeX table string with cellcolor injections.
    The colors perfectly mirror the fine-tuned terminal output gradients.
    Suitable for standard \begin{table} academic formatting.
    """
    alg_keys = list(ALGORITHMS_DATA.keys())
    
    # Escape special LaTeX characters in algorithm names (e.g., SIPP_2^2 -> SIPP\_2\textsuperscript{2})
    display_names = []
    for k in alg_keys:
        name = ALGORITHMS_DATA[k][0]
        if '^' in name:
            name = name.replace('^', r'\textsuperscript{').replace('_', r'\_') + '}'
        else:
            name = name.replace('_', r'\_')
        display_names.append(name)
    
    latex = [
        r"\begin{table}[h!]",
        r"\centering",
        r"\caption{" + title.replace('_', r'\_') + "}",
        r"\begin{tabular}{r" + "c" * len(alg_keys) + "}",
        r"\toprule",
        "Obstacles & " + " & ".join(display_names) + r" \\",
        r"\midrule"
    ]

    for row in data:
        vals = [row.get(alg, np.nan) for alg in alg_keys]
        valid_vals = [v for v in vals if pd.notnull(v) and v > 0]
        
        if not valid_vals: continue
        row_min, row_max = min(valid_vals), max(valid_vals)
        
        line = [f"{row.get('obstacles', '-')}"]
        
        for v in vals:
            if pd.isna(v) or v <= 0:
                line.append("---")
            else:
                r, g, b = get_flexible_gradient_bg(
                    v, row_min, row_max, 
                    log_iters=4,    
                    exp_iters=0,    
                    gamma=0.75       
                )
                
                # Convert the derived RGB tuple into HTML Hex format for the LaTeX \cellcolor macro
                hex_color = f"{r:02X}{g:02X}{b:02X}"
                text_color = "black" # Force black text for LaTeX documents regardless of cell darkness
                
                cell_code = r"\cellcolor[HTML]{" + hex_color + r"}\color{" + text_color + "}" + f"{v:.3f}x"
                line.append(cell_code)
        
        latex.append(" & ".join(line) + r" \\")

    latex.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}"
    ])
    
    return "\n".join(latex)

def generate_latex_blocks(data, title, gap_size="2pt"):
    """
    Generates a modern, aesthetically pleasing LaTeX block-table layout.
    By inflating row heights and column separators with white color gaps, 
    the heatmap cells are visually rendered as distinct floating squares.
    """
    alg_keys = list(ALGORITHMS_DATA.keys())
    
    # Escape algorithm names (handles circumflex natively via \string^)
    display_names = []
    for k in alg_keys:
        name = ALGORITHMS_DATA[k][0]
        if '^' in name:
            name = name.replace('^', '\\string^')
        else:
            name = name.replace('_', r'\_')
        display_names.append(name)
    
    # Inject '|' into column specifications to enable vertical gap sizing
    col_spec = "r | " + " | ".join(["c"] * len(alg_keys))
    
    latex = [
        r"\begin{table}[h!]",
        r"\centering",
        r"\caption{" + title.replace('_', r'\_') + "}",
        r"\setlength{\tabcolsep}{8pt}",       # Horizontal padding inside cells
        r"\renewcommand{\arraystretch}{1.5}", # Vertical multiplier (makes cells closer to perfect squares)
        r"\arrayrulecolor{white}",            # Forces table borders/rules to map to paper background
        f"\\setlength{{\\arrayrulewidth}}{{{gap_size}}}",
        r"\begin{tabular}{" + col_spec + "}",
        r"\toprule",
        r"\rowcolor{white} Obstacles & " + " & ".join(display_names) + r" \\ \hline",
    ]

    for row in data:
        vals = [row.get(alg, np.nan) for alg in alg_keys]
        valid_vals = [v for v in vals if pd.notnull(v) and v > 0]
        
        if not valid_vals: continue
        row_min, row_max = min(valid_vals), max(valid_vals)
        
        line = [f"\\rowcolor{{white}} {row.get('obstacles', '-')}"]
        
        for v in vals:
            if pd.isna(v) or v <= 0:
                line.append(r"\cellcolor{gray!10} ---")
            else:
                r, g, b = get_flexible_gradient_bg(
                    v, row_min, row_max, 
                    log_iters=6,    
                    exp_iters=0,    
                    gamma=0.7       
                )
                
                hex_color = f"{r:02X}{g:02X}{b:02X}"
                text_color = "black"
                
                # Assemble the colored cell code
                cell_code = r"\cellcolor[HTML]{" + hex_color + r"}\color{" + text_color + "}" + f"{v:.3f}x"
                line.append(cell_code)
        
        # Append an \hline to every row to establish horizontal white gaps
        latex.append(" & ".join(line) + r" \\ \hline")

    latex.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}"
    ])
    
    return "\n".join(latex)
